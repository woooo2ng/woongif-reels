# 역할별 한 번에 뽑은 음성을 대사 단위로 자름 (silencedetect 구간)
import subprocess, os
os.makedirs('lines', exist_ok=True)
R = {
 'raw/nar.mp3': {'n1':(0,3.75),'n2':(4.27,10.54),'n3':(11.0,14.71),'n4':(15.14,19.34),'n6':(23.79,27.51),'n7':(28.07,33.95),'n8':(34.42,36.14)},
 'raw/eg.mp3': {'g1':(0,1.52),'g2':(2.05,5.73),'g3':(5.91,6.58),'gc':(6.71,8.0)},
 'raw/ig.mp3': {'k1':(0,1.38),'k2':(2.27,5.57)},
 'raw/es.mp3': {'e1':(0,4.13),'e2':(4.52,6.81),'e3':(7.20,9.29),'ec':(9.51,10.81)},
 'raw/es2.mp3': {'e4':(0,4.36)},
 'raw/is2.mp3': {'s4':(0,4.24),'s5':(5.14,8.45),'s6':(9.21,9.83)},
 'raw/nar2.mp3': {'n9':(0,3.74)},
 'raw/nar3.mp3': {'n5':(0,4.32)},
 'raw/is.mp3': {'s1':(0.17,1.78),'s2':(2.10,5.15),'s3':(5.78,6.97)},
}
for f, d in R.items():
    for k, (a, b) in d.items():
        subprocess.run(['ffmpeg','-y','-loglevel','error','-i',f,'-ss',f'{max(0,a-0.03):.3f}','-to',f'{b+0.06:.3f}','-ar','48000','-ac','1',f'lines/{k}.wav'],check=True)
        print(k, round(b-a,2))
