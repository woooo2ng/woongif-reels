import subprocess, os
os.makedirs('lines', exist_ok=True)
R = {
 'raw/nar.mp3': {'n1':(0,3.93),'n2':(4.50,8.57),'n3':(9.17,11.96),'n4':(12.49,16.38),'n5':(17.0,22.13),'n6':(22.76,27.93),'n7':(28.61,34.66),'n8':(35.32,43.30)},
 'raw/eg.mp3': {'g1':(0,5.35),'g2':(6.06,10.22),'g3':(11.06,13.13),'g4':(14.09,15.76)},
 'raw/ig.mp3': {'k1':(0,1.13),'k2':(3.12,3.92),'k3':(4.71,6.48),'k4':(7.08,8.30)},
 'raw/es.mp3': {'e1':(0,3.54),'e2':(3.91,7.39),'e3':(7.66,9.81),'e5':(10.17,14.21),'e6':(14.49,19.99),'e7':(20.26,20.68)},
 'raw/es2.mp3': {'e4':(0,2.768980)},
 'raw/is.mp3': {'s1':(0,1.12),'s2':(1.70,2.41),'s3':(3.05,3.72),'s4':(4.25,5.67)},
}
for f, d in R.items():
    for k, (a, b) in d.items():
        subprocess.run(['ffmpeg','-y','-loglevel','error','-i',f,'-ss',f'{max(0,a-0.03):.3f}','-to',f'{b+0.06:.3f}','-ar','48000','-ac','1',f'lines/{k}.wav'],check=True)
        print(k, round(b-a,2))
