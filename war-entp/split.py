# 역할별로 한 번에 뽑은 음성을 대사 단위로 자름 (silencedetect 구간)
import subprocess, os
os.makedirs('lines', exist_ok=True)
R = {
 'raw/nar.mp3': {'n1':(0,3.02),'n2':(3.51,6.33),'n3':(6.87,13.80),'n4':(14.28,18.04),'n5':(18.57,21.19),'n6':(21.67,25.6)},
 'raw/gen.mp3': {'g1':(0,3.65),'g2':(4.17,4.64),'g3':(5.24,6.87),'g4':(7.41,10.03),'g5':(10.68,14.39),'g6':(15.04,17.76)},
 'raw/ej.mp3': {'e1':(0,2.56),'e2':(3.38,5.06),'e3':(5.52,6.01),'e4':(6.51,7.74),'e5a':(8.39,10.25),'e5b':(10.61,11.17),'e6':(11.66,14.59),'e7':(15.08,16.88)},
 'raw/sol.mp3': {'s1':(0,1.96),'s2':(2.54,5.52),'s3':(5.96,7.67),'s4':(8.30,10.00),'s5':(10.41,12.09),'s6':(12.68,14.80),'s7':(15.27,15.50),'sc':(16.05,18.48)},
 'raw/foe.mp3': {'f1':(0,0.80),'f2':(1.12,4.89),'fc':(5.16,7.04)},
}
for f, d in R.items():
    for k, (a, b) in d.items():
        subprocess.run(['ffmpeg','-y','-loglevel','error','-i',f,'-ss',f'{max(0,a-0.03):.3f}','-to',f'{b+0.06:.3f}','-ar','48000','-ac','1',f'lines/{k}.wav'],check=True)
        print(k, round(b-a,2))
